#!/usr/bin/env python3
"""
Evaluate Coder Agent Performance across all runs.

Metrics:
1. Code Execution Success Rate
   - Counts coder_agent appearances in groupchat logs
   - Counts code_executor_agent responses with "exitcode: 0"
   - Calculates success rate

2. Feature Correctness (Hallucination Detection)
   - Extracts conversation before each coder_agent call
   - Uses LLM to analyze if code uses features not in conversation
   - Calculates hallucination rate (wrong feature selection %)

Output: JSON file with detailed results and overall metrics
"""
import sys
import json
import os
from pathlib import Path
from typing import Dict, List, Tuple
import re

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from utils.aoai_chat import get_chat_response

def find_all_groupchat_logs(base_dir: str) -> List[Path]:
    """Find all groupchat log files in the response directory."""
    base_path = Path(base_dir)
    groupchat_logs = []
    
    for log_file in base_path.rglob("groupchat_logs/groupchat_log_*.json"):
        groupchat_logs.append(log_file)
    
    return groupchat_logs

def analyze_code_execution(groupchat_data: List[Dict]) -> Tuple[int, int]:
    """
    Analyze code execution success rate.
    
    Returns:
        Tuple[int, int]: (successful_executions, total_executions)
    """
    coder_agent_present = False
    total_executions = 0
    successful_executions = 0
    
    for message in groupchat_data:
        # Check if coder_agent is present
        if message.get("name") == "coder_agent":
            coder_agent_present = True
        
        # Check code_executor_agent responses
        if message.get("name") == "code_executor_agent":
            content = message.get("content", "")
            total_executions += 1
            
            # Check for exitcode: 0 (success)
            if "exitcode: 0" in content.lower():
                successful_executions += 1
    
    return successful_executions, total_executions

def extract_conversation_before_coder(groupchat_data: List[Dict], coder_index: int) -> str:
    """Extract conversation before a coder_agent message."""
    conversation = []
    for i in range(coder_index):
        msg = groupchat_data[i]
        name = msg.get("name", "unknown")
        content = msg.get("content", "")
        conversation.append(f"{name}: {content}")
    
    return "\n\n".join(conversation)

def evaluate_feature_correctness(previous_conversation: str, coder_code: str) -> Dict:
    """
    Use LLM to evaluate feature correctness in generated code.
    
    Returns:
        Dict with total_features, hallucinated_features
    """
    prompt = f"""You are evaluating code generated by an AI coding agent.

Given:
1. Previous conversation context (information available to the coder)
2. Code generated by the coder agent

Task: Analyze if the code uses features/variables/data that were NOT provided in the previous conversation.

Previous Conversation:
{previous_conversation}

Code Generated by Coder Agent:
{coder_code}

Instructions:
1. Identify all features/variables/data/parameters used in the code (e.g., column names, variable names, API parameters, data fields)
2. Check if each feature was mentioned or derivable from the previous conversation
3. Count total features used
4. Count features that appear to be hallucinated (not mentioned in conversation)

Return ONLY a JSON object with this exact format:
{{"total_features": 0, "hallucinated_features": 0, "hallucinated_list": [], "explanation": "brief explanation"}}"""

    try:
        response = get_chat_response(
            messages=[{"role": "user", "content": prompt}],
            # temperature=0.0,
            # max_tokens=1000
        )
        
        # Extract JSON from response
        content = response.strip()
        
        # Try to find JSON in markdown code blocks
        json_match = re.search(r'```(?:json)?\s*(\{.*?\})\s*```', content, re.DOTALL)
        if json_match:
            content = json_match.group(1)
        
        # Parse JSON
        result = json.loads(content)
        return result
        
    except Exception as e:
        print(f"Error in LLM evaluation: {e}")
        return {
            "total_features": 0,
            "hallucinated_features": 0,
            "hallucinated_list": [],
            "explanation": f"Error: {str(e)}"
        }

def analyze_groupchat_log(log_file: Path) -> Dict:
    """Analyze a single groupchat log file."""
    try:
        with open(log_file, 'r', encoding='utf-8') as f:
            groupchat_data = json.load(f)
        
        # 1. Code execution analysis
        successful_execs, total_execs = analyze_code_execution(groupchat_data)
        
        # 2. Feature correctness analysis
        feature_analyses = []
        
        for idx, message in enumerate(groupchat_data):
            if message.get("name") == "coder_agent":
                # Extract code from coder_agent message
                coder_code = message.get("content", "")
                
                # Get previous conversation
                previous_conv = extract_conversation_before_coder(groupchat_data, idx)
                
                # Evaluate feature correctness
                if coder_code.strip():
                    feature_result = evaluate_feature_correctness(previous_conv, coder_code)
                    feature_analyses.append(feature_result)
        
        return {
            "log_file": str(log_file.relative_to(log_file.parents[3])),
            "successful_executions": successful_execs,
            "total_executions": total_execs,
            "success_rate": successful_execs / total_execs if total_execs > 0 else 0,
            "feature_analyses": feature_analyses,
            "num_coder_calls": len(feature_analyses)
        }
        
    except Exception as e:
        print(f"Error analyzing {log_file}: {e}")
        return None

def calculate_overall_metrics(results: List[Dict]) -> Dict:
    """Calculate overall metrics from all results, using only logs where coder was called."""
    # Filter to only results where coder was called (num_coder_calls > 0)
    results_with_coder = [r for r in results if r and r.get("num_coder_calls", 0) > 0]
    
    total_successful = 0
    total_executions = 0
    total_features = 0
    total_hallucinated = 0
    
    for result in results_with_coder:
        total_successful += result["successful_executions"]
        total_executions += result["total_executions"]
        
        for analysis in result["feature_analyses"]:
            total_features += analysis.get("total_features", 0)
            total_hallucinated += analysis.get("hallucinated_features", 0)
    
    overall_success_rate = total_successful / total_executions if total_executions > 0 else 0
    hallucination_rate = total_hallucinated / total_features if total_features > 0 else 0
    
    return {
        "total_groupchat_logs": len(results),
        "logs_with_coder_calls": len(results_with_coder),
        "logs_without_coder_calls": len(results) - len(results_with_coder),
        "code_execution": {
            "total_executions": total_executions,
            "successful_executions": total_successful,
            "success_rate": overall_success_rate,
            "success_rate_percent": f"{overall_success_rate * 100:.2f}%"
        },
        "feature_correctness": {
            "total_features_used": total_features,
            "hallucinated_features": total_hallucinated,
            "correct_features": total_features - total_hallucinated,
            "hallucination_rate": hallucination_rate,
            "hallucination_rate_percent": f"{hallucination_rate * 100:.2f}%",
            "correctness_rate_percent": f"{(1 - hallucination_rate) * 100:.2f}%"
        }
    }

def main():
    """Main execution function."""
    import argparse
    
    parser = argparse.ArgumentParser(description="Evaluate Coder Agent Performance")
    parser.add_argument(
        "--input-dir",
        type=str,
        default=r"./final_testing_codes\task_scenario_new_final_1_responses",
        help="Base directory containing groupchat logs"
    )
    parser.add_argument(
        "--output-file",
        type=str,
        default="final_evals/FINAL_OUTCOMES/CODING/coder_agent_evaluation_results.json",
        help="Output JSON file name (e.g., 'coder_agent_evaluation_results.json' or 'results_baseline.json')"
    )
    
    args = parser.parse_args()
    
    base_dir = args.input_dir
    output_file = Path(args.output_file)
    
    print(f"Input Directory: {base_dir}")
    print(f"Output File: {output_file}")
    print("="*80)
    
    print("\nFinding all groupchat logs...")
    log_files = find_all_groupchat_logs(base_dir)
    print(f"Found {len(log_files)} groupchat logs to analyze\n")
    
    if not log_files:
        print("No groupchat logs found!")
        return
    
    print("Analyzing groupchat logs...")
    results = []
    
    for i, log_file in enumerate(log_files, 1):
        print(f"[{i}/{len(log_files)}] Analyzing {log_file.relative_to(Path(base_dir).parent)}...")
        result = analyze_groupchat_log(log_file)
        if result:
            results.append(result)
            print(f"  Code Success: {result['successful_executions']}/{result['total_executions']}, "
                  f"Coder Calls: {result['num_coder_calls']}")
    
    print("\n" + "="*80)
    print("OVERALL METRICS (Only logs where coder was called)")
    print("="*80)
    
    overall = calculate_overall_metrics(results)
    
    print(f"\nTotal Logs Analyzed: {overall['total_groupchat_logs']}")
    print(f"Logs with Coder Calls: {overall['logs_with_coder_calls']}")
    print(f"Logs without Coder Calls: {overall['logs_without_coder_calls']}")
    
    print("\n1. CODE EXECUTION SUCCESS RATE:")
    print(f"   Total Executions: {overall['code_execution']['total_executions']}")
    print(f"   Successful: {overall['code_execution']['successful_executions']}")
    print(f"   Success Rate: {overall['code_execution']['success_rate_percent']}")
    
    print("\n2. FEATURE CORRECTNESS (HALLUCINATION RATE):")
    print(f"   Total Features Used: {overall['feature_correctness']['total_features_used']}")
    print(f"   Hallucinated Features: {overall['feature_correctness']['hallucinated_features']}")
    print(f"   Correct Features: {overall['feature_correctness']['correct_features']}")
    print(f"   Hallucination Rate: {overall['feature_correctness']['hallucination_rate_percent']}")
    print(f"   Correctness Rate: {overall['feature_correctness']['correctness_rate_percent']}")
    
    # Save detailed results
    output_file.parent.mkdir(exist_ok=True, parents=True)
    
    output_data = {
        "overall_metrics": overall,
        "detailed_results": results
    }
    
    with open(output_file, 'w', encoding='utf-8') as f:
        json.dump(output_data, f, indent=2, ensure_ascii=False)
    
    print(f"\n✓ Detailed results saved to: {output_file.absolute()}")
    print("="*80)

if __name__ == "__main__":
    main()
